export const getProjectStatsFrom = (
  visibleProjects: readonly ProjectSummaryDto[],
): ProjectListStatsDto => ({
  total_count: visibleProjects.length,
  active_count: visibleProjects.filter((project) => project.status === 'active')
    .length,
  paused_count: visibleProjects.filter((project) => project.status === 'paused')
    .length,
  archived_count: visibleProjects.filter(
    (project) => project.status === 'archived',
  ).length,
  risk_count: visibleProjects.filter(
    (project) => project.health_status === 'risk',
  ).length,
})

export const getProjectNavigationFor = (
  project: ProjectSummaryDto,
): ProjectNavigationDto => {
  const config = projectTypeConfigs.find(
    (item) => item.method === project.method,
  )
  const enabledTabs =
    config?.tabs
      .filter((tab) => tab.enabled)
      .sort((first, second) => first.sort_order - second.sort_order)
      .map((tab) => ({
        tab_key: tab.tab_key,
        name: tab.name,
        route: `/projects/${project.id}/${tab.route_name}`,
        module_key: tab.module_key,
        enabled: tab.enabled,
        available: true,
      })) ?? []

  return {
    project,
    tabs: enabledTabs.slice(0, 6),
    more_tabs: enabledTabs.slice(6),
    system_entries: [
      {
        tab_key: 'configuration',
        name: '项目配置',
        route: `/projects/${project.id}/configuration`,
        module_key: 'configuration',
        enabled: true,
        available: true,
      },
    ],
    quick_actions: ['创建工作项', '创建需求', '创建任务', '创建缺陷'],
  }
}

